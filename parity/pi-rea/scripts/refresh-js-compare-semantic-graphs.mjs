#!/usr/bin/env bun
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { canonicalJson, sha256Hex } from '../../../extensions/pi-rea/src/analysis/canonical.mjs';
import { ensureJsCompareFixtures } from './lib/ensure-fixtures.mjs';
import { classifyOracle, invokeReaAgentsCli } from './lib/invoke-rea-agents.mjs';
import { NOTEPAD_APP } from './lib/paths.mjs';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../../extensions/pi-rea/src/analysis/formats/semantic-graph-fixtures/encoded.mjs');

function sealOk(graph) {
  const { graph_id: identifier, ...semantic } = graph;
  const expected = `jsrg_${sha256Hex(canonicalJson(semantic))}`;
  if (identifier !== expected) throw new Error(`stale graph_id ${identifier}`);
  for (const node of graph.nodes) {
    const nodeId = `jsrg_node_${sha256Hex(canonicalJson({ kind: node.kind, identity: node.identity }))}`;
    if (node.node_id !== nodeId) throw new Error(`stale node_id ${node.node_id}`);
  }
}

async function measureSemanticGraph(label, path) {
  const oracle = classifyOracle((await invokeReaAgentsCli(['analyze-javascript-application', path, '--artifact-format', 'directory'])).parsed);
  const graph = oracle.body.normalized_result.semantic_graph;
  if (graph === undefined || graph === null) throw new Error(`${label}: oracle missing semantic_graph`);
  sealOk(graph);
  process.stdout.write(`${label}: root=${graph.root_artifact_sha256} nodes=${graph.nodes.length} relations=${graph.relations.length}\n`);
  return graph;
}

const { left, right } = ensureJsCompareFixtures();
const graphs = {
  left: await measureSemanticGraph('left', left),
  right: await measureSemanticGraph('right', right),
  notepad: await measureSemanticGraph('notepad', NOTEPAD_APP),
};

const leftB64 = Buffer.from(JSON.stringify(graphs.left)).toString('base64');
const rightB64 = Buffer.from(JSON.stringify(graphs.right)).toString('base64');
const notepadB64 = Buffer.from(JSON.stringify(graphs.notepad)).toString('base64');
writeFileSync(
  OUT,
  `/** Measured semantic_graph goldens (base64). Regenerated by refresh-js-compare-semantic-graphs.mjs. */
export const JS_COMPARE_LEFT_SEMANTIC_GRAPH_B64 = ${JSON.stringify(leftB64)};
export const JS_COMPARE_RIGHT_SEMANTIC_GRAPH_B64 = ${JSON.stringify(rightB64)};
export const NOTEPAD_SEMANTIC_GRAPH_B64 = ${JSON.stringify(notepadB64)};
`,
);
process.stdout.write(`wrote ${OUT}\n`);
