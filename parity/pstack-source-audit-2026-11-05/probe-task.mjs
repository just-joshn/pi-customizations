import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';

const root = dirname(fileURLToPath(import.meta.url));
const repo = resolve(root, '../..');
const RAW = join(repo, '.audit/pstack-source-audit-2026-11-05/source');
const LIVE = join(repo, '.audit/pi-pstack-behavior-parity/cursor-evidence/task-schema.jsonl');
const hash = (text) => createHash('sha256').update(text).digest('hex');
const raw = (name) => readFileSync(join(RAW, name), 'utf8');

class Message {
  constructor(fields) {
    Object.assign(this, fields);
  }
}

// The flags the live CLI capture shows: client-side subagents, run_in_background in the schema, completion hints,
// catalogs in the user-info message, and no interrupt, self-fork, or chat links.
const LIVE_FLAGS = { u: true, W: true, G: true, Y: false, X: true, V: false, R: false, l: true, h: true, m: true, f: false, g: false, O: false, F: undefined };
const context = {
  $: new Proxy({}, { get: () => Message }),
  Hne: 'composer-2.5',
  Wne: 'composer-2.5-fast',
  f9: { DEFAULT: 0, LAST_AGENT_SAME_TYPE: 1 },
  yIe: 'self',
  ePe: '',
  kAe: () => undefined,
  ce: new Map(),
  n: {},
  H: { modelsBySlug: new Map([['inherit', { slug: 'inherit' }]]) },
  ae: 'Task',
  s: {},
  ...LIVE_FLAGS,
};
const build = runInNewContext(
  `${raw('desktop-agent-definitions.txt')}\n${raw('desktop-task-description-catalog.js')}\nconst o = Jle({ customSubagents: [], includeExploreSubagent: true, includeBestOfNRunnerSubagent: false });\n(${raw('desktop-task-description.js').trim()})`,
  context,
);
const description = build({ allTools: { READ: { name: 'Read' }, GLOB: { name: 'Glob' }, AWAIT: { name: 'AwaitShell' } } }, true).fullDescription;

const result = { description, parameters: undefined, liveCapture: undefined };
if (existsSync(LIVE)) {
  const lines = readFileSync(LIVE, 'utf8').trim().split('\n');
  const record = lines.map((line) => JSON.parse(line)).find((entry) => JSON.stringify(entry).includes('Launch a new agent to handle complex'));
  const tool = JSON.parse(record.tool_call.getMcpToolsToolCall.result.success.content);
  assert.equal(tool.tool, 'Task');
  assert.equal(description, tool.description, 'desktop template with the live flags reproduces the live CLI description');
  result.parameters = Object.fromEntries(Object.entries(tool.inputSchema.properties).map(([name, value]) => [name, value.description]));
  result.liveCapture = { file: '.audit/pi-pstack-behavior-parity/cursor-evidence/task-schema.jsonl', sha256: hash(readFileSync(LIVE)) };
}
assert.ok(result.parameters, 'the live CLI capture supplies the parameter descriptions');
const fixturePath = join(repo, 'extensions/pi-pstack/test/fixtures/cursor-agent-definitions.json');
const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));
fixture.task = {
  source:
    'Cursor desktop 3.27.22 Task description builder (oPe) run with the flags of a live Cursor CLI session, checked equal to that session; parameter descriptions from the same session. Generated by parity/pstack-source-audit-2026-11-05/probe-task.mjs.',
  sources: [...['desktop-task-description-catalog.js', 'desktop-task-description.js'].map((file) => ({ file: `.audit/pstack-source-audit-2026-11-05/source/${file}`, sha256: hash(raw(file)) })), result.liveCapture],
  description: result.description,
  parameters: result.parameters,
};
writeFileSync(fixturePath, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(JSON.stringify({ descriptionLength: description.length, matchesLive: true, parameters: Object.keys(result.parameters) }, null, 2));
