// Records the tool text a live Cursor CLI session declared for the tools pi-pstack reproduces, as a test oracle.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const repo = resolve(root, '../..');
const file = '.audit/pi-pstack-behavior-parity/cursor-evidence/dynamic-tool-schemas.jsonl';
const bytes = readFileSync(join(repo, file));
const tools = {};
const walk = (value) => {
  if (typeof value === 'string' && value.startsWith('{"tool":')) {
    const tool = JSON.parse(value);
    if (['TodoWrite', 'SwitchMode', 'GenerateImage', 'AwaitShell'].includes(tool.tool) && tools[tool.tool] === undefined)
      tools[tool.tool] = {
        description: tool.description,
        parameters: Object.fromEntries(Object.entries(tool.inputSchema.properties).map(([name, schema]) => [name, schema.description])),
        required: tool.inputSchema.required ?? [],
      };
  } else if (value !== null && typeof value === 'object') for (const child of Object.values(value)) walk(child);
};
for (const line of bytes.toString('utf8').trim().split('\n')) walk(JSON.parse(line));
assert.deepEqual(Object.keys(tools).toSorted(), ['AwaitShell', 'GenerateImage', 'SwitchMode', 'TodoWrite']);

// AskQuestion has no declared schema in the captures, so its text comes from the string literals of desktop's
// AskQuestion tool: the default description (not the anti-AskQuestion variant) and the schema's describe() texts.
const DESKTOP = '/usr/share/cursor/resources/app/extensions/cursor-local-agent-runtime/dist/main.js';
const desktopSource = readFileSync(DESKTOP, 'utf8');
const { parse } = createRequire(import.meta.url)(join(repo, 'node_modules/.bun/@babel+parser@7.29.9/node_modules/@babel/parser/lib/index.js'));
const literals = [];
const collect = (node) => {
  if (node === null || typeof node !== 'object') return;
  if (node.type === 'StringLiteral') literals.push(node.value);
  for (const [key, value] of Object.entries(node)) {
    if (key === 'loc') continue;
    if (Array.isArray(value)) for (const child of value) collect(child);
    else if (value !== null && typeof value === 'object' && typeof value.type === 'string') collect(value);
  }
};
collect(parse(desktopSource, { sourceType: 'script', errorRecovery: true, allowReturnOutsideFunction: true }).program);
const only = (predicate, label) => {
  const found = [...new Set(literals.filter(predicate))];
  assert.equal(found.length, 1, `${label}: ${found.length} literals`);
  return found[0];
};
tools.AskQuestion = {
  description: only((value) => value.startsWith('Collect structured multiple-choice answers from the user. Use this tool only when'), 'AskQuestion description'),
  parameters: {
    title: only((value) => value === 'Optional title for the questions form', 'title'),
    questions: only((value) => value === 'Array of questions to present to the user (minimum 1 required)', 'questions'),
    'questions.id': only((value) => value === 'Unique identifier for this question', 'question id'),
    'questions.prompt': only((value) => value === 'The question text to display to the user, without the options.', 'question prompt'),
    'questions.options': only((value) => value === 'Array of answer options (minimum 2 required)', 'options'),
    'questions.options.id': only((value) => value === 'Unique identifier for this option', 'option id'),
    'questions.options.label': only((value) => value === 'Display text for this option', 'option label'),
    'questions.allow_multiple': only((value) => value === 'If true, user can select multiple options. Defaults to false.', 'allow_multiple'),
  },
  required: ['questions'],
};
const fixture = {
  source:
    'Tool descriptions and parameter descriptions a live Cursor CLI session declared (GetDynamicTools results), and AskQuestion text from desktop 3.27.22 string literals. Generated by parity/pstack-source-audit-2026-11-05/probe-tools.mjs.',
  capture: { file, sha256: createHash('sha256').update(bytes).digest('hex') },
  desktop: { file: DESKTOP, sha256: createHash('sha256').update(desktopSource).digest('hex') },
  tools,
};
writeFileSync(join(repo, 'extensions/pi-pstack/test/fixtures/cursor-tool-text.json'), `${JSON.stringify(fixture, null, 2)}\n`);
console.log(
  Object.entries(tools)
    .map(([name, tool]) => `${name}: ${tool.description.length} chars, ${Object.keys(tool.parameters).join(', ')}`)
    .join('\n'),
);
