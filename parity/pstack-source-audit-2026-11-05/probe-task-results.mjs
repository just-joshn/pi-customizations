// Runs Cursor desktop agent host's Task result renderer on fixed inputs and records the texts as a test oracle.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';

const root = dirname(fileURLToPath(import.meta.url));
const repo = resolve(root, '../..');
const RAW = '.audit/pstack-source-audit-2026-11-05/source';
const names = ['daemon-task-result-render.js', 'daemon-task-result-text.js', 'daemon-task-background-text.js'];
const code = names.map((name) => readFileSync(join(repo, RAW, name), 'utf8')).join('\n');
const SubagentBackgroundReason = { UNSPECIFIED: 0, AGENT_REQUEST: 1, USER_REQUEST: 2, QUEUED_FOLLOW_UP: 3 };
const render = runInNewContext(`${code}\nrenderTaskResultToString`, {
  SubagentBackgroundReason,
  RUNNING_SUBAGENT_FOLLOWUP_ERROR: 'Sub-agent is currently running. You may send the follow-up message when it has completed.',
});

// The CLI agent type: no chat links, and job completion notifications on, as the live session's texts show.
const options = { enableAgentChatLinks: false, enableJobCompletionNotifications: true };
const agentId = '11111111-2222-4333-8444-555555555555';
const step = (text) => ({ message: { case: 'assistantMessage', value: { text } } });
const cases = [
  { name: 'foreground', response: 'DONE', background: false },
  { name: 'foreground without output', response: undefined, background: false },
  { name: 'foreground preformatted', response: '<response>\nALREADY\n</response>', background: false },
  { name: 'foreground with suffix', response: 'DONE', background: false, suffix: 'Note: n' },
  { name: 'background with transcript', background: true, transcript: '/s/x.jsonl' },
];
const results = cases.map((entry) => ({
  ...entry,
  agentId,
  text: render(
    {
      result: {
        case: 'success',
        value: {
          agentId,
          conversationSteps: entry.response === undefined ? [] : [step(entry.response)],
          backgroundReason: entry.background ? SubagentBackgroundReason.AGENT_REQUEST : SubagentBackgroundReason.UNSPECIFIED,
          transcriptPath: entry.transcript,
          resultSuffix: entry.suffix,
        },
      },
    },
    options,
  ),
}));
const fixturePath = join(repo, 'extensions/pi-pstack/test/fixtures/cursor-agent-definitions.json');
const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));
fixture.taskResults = {
  source:
    'Cursor desktop 3.27.22 agent host renderTaskResultToString, getTaskSuccessResultText, and formatSubagentBackgroundMessage, run with chat links off and job completion notifications on. Generated by parity/pstack-source-audit-2026-11-05/probe-task-results.mjs.',
  sources: names.map((name) => ({
    file: `${RAW}/${name}`,
    sha256: createHash('sha256')
      .update(readFileSync(join(repo, RAW, name)))
      .digest('hex'),
  })),
  cases: results,
};
writeFileSync(fixturePath, `${JSON.stringify(fixture, null, 2)}\n`);
for (const entry of results) console.log(`## ${entry.name}\n${entry.text}\n`);
