import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const out = process.argv[2];
const child = spawn(process.env.PI_BIN ?? 'pi', ['--mode', 'rpc', '--no-session'], { stdio: ['pipe', 'pipe', 'pipe'] });
const lines = []; let buf = '';
child.stdout.on('data', (d) => { buf += d; let i; while ((i = buf.indexOf('\n')) >= 0) { const l = buf.slice(0, i); buf = buf.slice(i + 1); try { lines.push(JSON.parse(l)); } catch { lines.push({ raw: l }); } } });
let stderr = ''; child.stderr.on('data', (d) => { stderr += d; });
const send = (o) => child.stdin.write(`${JSON.stringify(o)}\n`);
const waitFor = (pred, ms = 20000) => new Promise((res, rej) => { const t0 = Date.now(); const iv = setInterval(() => { const hit = lines.find(pred); if (hit) { clearInterval(iv); res(hit); } else if (Date.now() - t0 > ms) { clearInterval(iv); rej(new Error('timeout')); } }, 50); });
send({ id: 'c', type: 'get_commands' });
const cmds = await waitFor((l) => l.id === 'c');
send({ id: 'm1', type: 'prompt', message: '/mode poteto-mode' });
await waitFor((l) => l.id === 'm1');
await new Promise((r) => setTimeout(r, 1500));
send({ id: 'm2', type: 'prompt', message: '/mode' });
await waitFor((l) => l.id === 'm2');
await new Promise((r) => setTimeout(r, 1500));
child.stdin.end();
await new Promise((r) => child.on('exit', r));
const names = cmds.data.commands.map((c) => `${c.source ?? ''}:${c.name}`);
writeFileSync(out, JSON.stringify({ commandCount: names.length, names, events: lines.filter((l) => l.id !== 'c'), stderr }, null, 2));
console.log(names.length, 'commands');
