// The release gate trusts a recorded run only for the code it ran against, and a failed test in the run closes it whether or not a requirement links the test.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { afterEach, describe, expect, test } from 'vitest';
import { type MiniRoot, miniRoot, script } from './helpers.ts';

let mini: MiniRoot;
afterEach(() => mini?.cleanup());

const INPUTS: Record<string, string> = {
  'adapters/cursor.ts': 'export const a = 1;\n',
  'generated/skills/x/SKILL.md': '# compiled\n',
  'package.json': '{"name":"p"}\n',
  'vitest.config.ts': 'export default {};\n',
  'tsconfig.json': '{}\n',
  'native/helper.c': 'int main(){return 0;}\n',
  'src/code.ts': 'export {};\n',
  'scripts/tool.mjs': '// tool\n',
};
const gitAdd = () => execFileSync('git', ['add', '-A'], { cwd: mini.root });
const gate = () => script('check-release.mjs', ['--root', mini.root]);
const build = (report: string, ...extra: string[]) => script('build-parity-manifest.mjs', ['--root', mini.root, '--results', report, ...extra]);

function builtRoot(tests: Record<string, string> = { 'suite passes': 'passed' }): void {
  mini = miniRoot();
  execFileSync('git', ['init', '-q'], { cwd: mini.root });
  for (const [path, text] of Object.entries(INPUTS)) mini.write(path, text);
  mkdirSync(join(mini.root, 'docs'), { recursive: true });
  gitAdd();
  const built = build(mini.report(tests), '--no-docs');
  expect(built.status, built.stderr).toBe(0);
}

describe('evidence is bound to every input the tests ran against', () => {
  test('the unchanged tree is accepted', () => {
    builtRoot();
    const r = gate();
    expect(r.status, r.stderr).toBe(0);
  });

  test.each(Object.keys(INPUTS))('a change to %s makes the recorded run stale', (path) => {
    builtRoot();
    writeFileSync(join(mini.root, path), `${INPUTS[path]}// changed after the run\n`);
    gitAdd();
    const r = gate();
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('stale, it ran against code that has since changed');
  });

  test('a change to the vendored upstream tree makes the recorded run stale', () => {
    builtRoot();
    writeFileSync(join(mini.root, 'vendor/upstream-pstack/skills/x/other.md'), 'new vendored file\n');
    gitAdd();
    expect(gate().stderr).toContain('stale, it ran against code that has since changed');
  });

  test('a CI result recorded against the code before an adapter change cannot establish PASS afterwards', () => {
    builtRoot({ 'suite passes': 'skipped' });
    const ci = join(mini.root, 'ci.json');
    writeFileSync(ci, JSON.stringify({ numTotalTests: 1, testResults: [{ name: '/runner/pkg/tests/t.test.ts', status: 'passed', assertionResults: [{ fullName: 'suite passes', status: 'passed' }] }] }));
    const digest = JSON.parse(readFileSync(join(mini.root, 'generated/parity-manifest.json'), 'utf8')).run['sourceDigest'];
    writeFileSync(join(mini.root, 'ci.identity.json'), JSON.stringify({ platform: 'linux', commit: 'c'.repeat(40), sourceDigest: digest, runUrl: 'https://github.com/o/r/actions/runs/1', root: '/runner/pkg' }));
    expect(build(ci, '--no-docs').status).toBe(0);
    expect(gate().status).toBe(0);
    writeFileSync(join(mini.root, 'adapters/cursor.ts'), 'export const a = 2;\n');
    gitAdd();
    const r = gate();
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('stale, it ran against code that has since changed');
  });

  test('the results the gate reads do not bind themselves: rebuilding the manifest, its docs section, and the result files change nothing', () => {
    builtRoot();
    mini.write('docs/parity-status.md', '# Status\n\n<!-- parity-status:begin (generated by scripts/build-parity-manifest.mjs; do not edit) -->\n\nold\n\n<!-- parity-status:end -->\n');
    mini.write('parity-results/local/vitest-linux.json', '{}');
    gitAdd();
    const built = build(mini.report({ 'suite passes': 'passed' }));
    expect(built.status, built.stderr).toBe(0);
    gitAdd();
    const r = gate();
    expect(r.status, r.stderr).toBe(0);
  });
});

describe('the release gate fails closed without a fingerprint', () => {
  const editRun = (edit: (run: Record<string, unknown>) => void): void => {
    const path = join(mini.root, 'generated/parity-manifest.json');
    const manifest = JSON.parse(readFileSync(path, 'utf8'));
    edit(manifest.runs[0]);
    writeFileSync(path, JSON.stringify(manifest));
  };

  test('a local result with no recorded source digest closes the gate', () => {
    builtRoot();
    editRun((run) => {
      expect(run['resultsSource']).not.toBe('ci');
      delete run['sourceDigest'];
    });
    const r = gate();
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('no source digest recorded');
  });

  test('a local result whose digest is not a sha256 closes the gate', () => {
    builtRoot();
    editRun((run) => {
      run['sourceDigest'] = 'not-a-digest';
    });
    const r = gate();
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('no source digest recorded');
  });

  test('a digest-less result stays closed when the current tree cannot be hashed', () => {
    builtRoot();
    editRun((run) => {
      delete run['sourceDigest'];
    });
    rmSync(join(mini.root, '.git'), { recursive: true });
    const r = gate();
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('cannot be hashed now');
  });

  test('a result with a digest stays closed when the current tree cannot be hashed', () => {
    builtRoot();
    rmSync(join(mini.root, '.git'), { recursive: true });
    const r = gate();
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('cannot be hashed now');
  });
});

describe('a failed test closes the gate whether or not a requirement links it', () => {
  const failingReport = (): string => {
    const path = join(mini.root, 'failing-report.json');
    writeFileSync(
      path,
      JSON.stringify({
        startTime: 1_700_000_000_000,
        numTotalTests: 2,
        numFailedTests: 1,
        testResults: [
          { name: join(mini.root, 'tests/t.test.ts'), status: 'passed', assertionResults: [{ fullName: 'suite passes', status: 'passed' }] },
          { name: join(mini.root, 'tests/unlinked.test.ts'), status: 'failed', assertionResults: [{ fullName: 'an unmapped behavior', status: 'failed' }] },
        ],
      }),
    );
    return path;
  };

  test('an unmapped failed test keeps the gate closed although every requirement is PASS, and the gate names it', () => {
    mini = miniRoot();
    execFileSync('git', ['init', '-q'], { cwd: mini.root });
    gitAdd();
    expect(build(failingReport(), '--no-docs').status).toBe(0);
    const manifest = JSON.parse(readFileSync(join(mini.root, 'generated/parity-manifest.json'), 'utf8'));
    expect(manifest.requirements.every((r: { status: string }) => r.status === 'PASS')).toBe(true);
    const r = gate();
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('tests/unlinked.test.ts::an unmapped behavior');
    expect(r.stderr).toContain('release gate: CLOSED');
  });

  test('a suite that failed to load, with no test of its own, keeps the gate closed', () => {
    mini = miniRoot();
    execFileSync('git', ['init', '-q'], { cwd: mini.root });
    gitAdd();
    const path = join(mini.root, 'broken-report.json');
    writeFileSync(path, JSON.stringify({ numTotalTests: 1, numFailedTests: 0, testResults: [{ name: join(mini.root, 'tests/t.test.ts'), status: 'passed', assertionResults: [{ fullName: 'suite passes', status: 'passed' }] }, { name: join(mini.root, 'tests/broken.test.ts'), status: 'failed', assertionResults: [] }] }));
    expect(build(path, '--no-docs').status).toBe(0);
    const r = gate();
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('tests/broken.test.ts');
  });

  test('a failed-test count that the recorded identities do not account for closes the gate', () => {
    builtRoot();
    const path = join(mini.root, 'generated/parity-manifest.json');
    const manifest = JSON.parse(readFileSync(path, 'utf8'));
    manifest.runs[0].failedTests = 3;
    writeFileSync(path, JSON.stringify(manifest));
    const r = gate();
    expect(r.status).toBe(1);
    expect(r.stderr).toMatch(/3 test\(s\) failed/);
  });

  test('a skipped or a missing mandatory test is INCONCLUSIVE, never PASS', () => {
    for (const tests of [{ 'suite passes': 'skipped' }, {}]) {
      mini = miniRoot();
      execFileSync('git', ['init', '-q'], { cwd: mini.root });
      gitAdd();
      expect(build(mini.report(tests), '--no-docs').status).toBe(0);
      const manifest = JSON.parse(readFileSync(join(mini.root, 'generated/parity-manifest.json'), 'utf8'));
      expect(manifest.requirements.map((r: { status: string }) => r.status)).toEqual(['INCONCLUSIVE', 'INCONCLUSIVE']);
      expect(gate().status).toBe(1);
      mini.cleanup();
    }
  });
});
