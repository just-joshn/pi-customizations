// The contract of every family: each check, the upstream source span it enforces, and the negative cases that must make it fail.
import { families } from './families/index.ts';
import { resolveSource } from './lib/check.ts';

const lines = ['# Workflow parity checks', '', 'Generated by `list-checks.ts`. Source spans point into `generated/skills`, the compiled upstream pin.', ''];
for (const family of families) {
  lines.push(`## ${family.id}`, '', family.title, '');
  if (family.requires !== undefined) lines.push(`Needs ${family.requires}; its absence is reported, never passed.`, '');
  for (const defect of family.knownDefects ?? []) lines.push(`Known product defect, asserted with test.fails: \`${defect.checkId}\`. ${defect.defect}`, '');
  lines.push('| Check | Contract | Source |', '| --- | --- | --- |');
  for (const check of family.checks) lines.push(`| \`${check.id}\` | ${check.title.replaceAll('|', '/')} | ${check.src.map((source) => `\`${resolveSource(source)}\``).join(', ')} |`);
  lines.push('', 'Negative cases, each of which must FAIL the named checks:', '');
  for (const negative of family.negatives) lines.push(`- ${negative.name} → ${negative.fails.map((id) => `\`${id}\``).join(', ')}`);
  lines.push('');
}
console.log(lines.map((line) => line.trimEnd()).join('\n'));
