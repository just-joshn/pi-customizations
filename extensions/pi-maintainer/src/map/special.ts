const NORMALIZED_ROOT_IMPORTANT_FILES = new Set(ROOT_IMPORTANT_FILES.map((path) => normalize(path)));

/** Aider `is_important` (`aider/special.py:184-193`). Case-sensitive basename/path match. */
export function isImportant(filePath: string): boolean {
  const fileName = basename(filePath);
  const dirName = normalize(dirname(filePath));
  const normalizedPath = normalize(filePath);
  if (dirName === normalize('.github/workflows') && fileName.endsWith('.yml')) return true;
  return NORMALIZED_ROOT_IMPORTANT_FILES.has(normalizedPath);
}

/** Aider `filter_important_files` (`aider/special.py:196-203`). */
export function filterImportantFiles(filePaths: readonly string[]): string[] {
  return filePaths.filter((path) => isImportant(path));
}
