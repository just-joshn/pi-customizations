const BASENAME_TO_LANG: Readonly<Record<string, string>> = {
  'CMakeLists.txt': 'cmake',
  Dockerfile: 'dockerfile',
  'go.mod': 'gomod',
  'go.sum': 'gosum',
  Kconfig: 'kconfig',
  Makefile: 'make',
  'meson.build': 'meson',
  'MANIFEST.in': 'pymanifest',
  qmldir: 'qmldir',
  'requirements.txt': 'requirements',
  BUILD: 'starlark',
  WORKSPACE: 'starlark',
};

export function filenameToLang(filename: string): string | undefined {
  const basename = filename.includes('/') ? filename.slice(filename.lastIndexOf('/') + 1) : filename;
  const byBasename = BASENAME_TO_LANG[basename];
  if (byBasename !== undefined) return byBasename;
  const dot = filename.lastIndexOf('.');
  if (dot <= 0) return undefined;
  return FILENAME_TO_LANG[filename.slice(dot)];
}
