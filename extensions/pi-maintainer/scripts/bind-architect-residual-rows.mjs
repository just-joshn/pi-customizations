#!/usr/bin/env node
// Fill pi/src/tests and mark verified for expressible architect residual rows.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const path = join(root, 'parity/ledger.json');
const ledger = JSON.parse(readFileSync(path, 'utf8'));

/** @type {Record<string, { pi: string[]; src: string[]; tests: string[] }>} */
const bindings = {
  'edit.architect.return-editor-cost': {
    pi: ['AgentSession.getSessionStats()', "pi.on('turn_end')", 'pi.registerVirtualModel'],
    src: ['src/core/exchange.ts', 'src/core/install.ts'],
    tests: ['test/core/modes.pi.test.ts::architect editor path starts from architect session cost and returns the accumulated total'],
  },
};

const updated = [];
for (const row of ledger.rows) {
  const binding = bindings[row.id];
  if (!binding || row.status === 'verified') continue;
  row.status = 'verified';
  row.pi = binding.pi;
  row.src = binding.src;
  row.tests = binding.tests;
  updated.push(row.id);
}

writeFileSync(path, `${JSON.stringify(ledger, null, 2)}\n`);
process.stdout.write(`verified ${updated.length} rows\n${updated.join('\n')}\n`);
