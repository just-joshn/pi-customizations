import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const catalogPath = new URL('../schemas/tool-contracts.json', import.meta.url);
const outputPath = new URL('../src/contract/handler-parameters.generated.ts', import.meta.url);
type Schema = Record<string, unknown>;

// Emit a conservative TypeScript representation: validation-only constraints narrow
// runtime values but cannot safely narrow their TypeScript primitive types.
const schemaType = (schema: Schema): string => {
  const parts: string[] = [];
  if (Array.isArray(schema['enum'])) parts.push(schema['enum'].map((value: unknown) => JSON.stringify(value)).join(' | ') || 'never');
  if ('const' in schema) parts.push(JSON.stringify(schema['const']));
  for (const key of ['anyOf', 'oneOf', 'allOf'] as const) {
    const entries = schema[key];
    if (Array.isArray(entries)) parts.push(`(${entries.map((entry: Schema) => schemaType(entry)).join(key === 'allOf' ? ' & ' : ' | ')})`);
  }
  const type = schema['type'];
  const primitive = (value: unknown): string => {
    switch (value) {
      case 'string':
        return 'string';
      case 'number':
      case 'integer':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'null':
        return 'null';
      case 'array':
        return `Array<${schema['items'] && typeof schema['items'] === 'object' ? schemaType(schema['items'] as Schema) : 'unknown'}>`;
      case 'object': {
        const properties = (schema['properties'] ?? {}) as Record<string, Schema>;
        const required = new Set(Array.isArray(schema['required']) ? schema['required'] : []);
        const fields = Object.entries(properties)
          .map(([name, value]) => `${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${schemaType(value)};`)
          .join(' ');
        const extra = schema['additionalProperties'];
        const index = extra === false ? '' : ` [key: string]: ${typeof extra === 'object' && extra !== null ? schemaType(extra as Schema) : 'unknown'};`;
        return `{ ${fields}${index} }`;
      }
      default:
        throw new Error(`Unsupported schema type: ${String(value)}`);
    }
  };
  if (Array.isArray(type)) parts.push(`(${type.map(primitive).join(' | ')})`);
  else if (type !== undefined) parts.push(primitive(type));
  return parts.length ? parts.map((part) => `(${part})`).join(' & ') : 'unknown';
};

export const generateHandlerTypes = (): string => {
  const catalog = JSON.parse(readFileSync(catalogPath, 'utf8')) as { tools: { name: string; implementation: string; parameters: Schema }[] };
  const entries = catalog.tools.filter((tool) => tool.implementation === 'kernel');
  if (new Set(entries.map((tool) => tool.name)).size !== entries.length) throw new Error('Duplicate kernel tool name');
  return `// Generated by scripts/generate-handler-types.ts from schemas/tool-contracts.json. Do not edit.\n// biome-ignore-all format: Generated output is kept compact.\n// biome-ignore-all lint/complexity/noBannedTypes: Empty schemas retain their existing non-nullish type.\nexport interface HandlerParameters {\n${entries.map((tool) => `  ${JSON.stringify(tool.name)}: ${schemaType(tool.parameters)};`).join('\n')}\n}\n`;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(outputPath, generateHandlerTypes());
